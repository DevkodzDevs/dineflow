const STOP = new Set(["with", "and", "the", "of", "a", "an", "nos", "no", "pcs", "pc", "plate", "half", "full", "special", "veg", "non", "style",
  // sizes and packs: "Veg biryani (family pack)" is a veg biryani
  "family", "pack", "regular", "large", "small", "mini", "jumbo", "single", "double"]);
/** Style words: they describe how a dish is made, not what it is, so they cannot match a dish on their own. */
const GENERIC = new Set(["masala", "curry", "fry", "fried", "rice", "roast", "gravy", "dry", "soup", "salad", "combo", "meals", "bowl", "mix", "sauce", "hot", "sweet", "spicy", "butter", "cream", "grilled", "tandoori", "chilli", "pepper", "garlic",
  "paratha", "dosa", "pulao", "biryani", "juice", "shake", "milkshake", "noodles", "pizza", "burger", "sandwich", "momos", "kebab", "tikka", "naan", "roti", "wrap", "roll", "pakoda", "cutlet", "chaat", "poriyal", "tea", "milk", "plain"]);
/** Words a menu hangs on the end of a name without changing the dish: "Fish curry meals" is a fish curry. */
const SUFFIX = new Set(["meals", "combo", "thali", "platter", "set", "bowl"]);
/** "Chicken Biryani (Family Pack)" → ["chicken", "biryani"]: what a menu calls a dish, boiled down to the words that name it. */
export function dishTokens(name: string): string[] {
  return name.toLowerCase().replace(/\([^)]*\)/g, " ").replace(/[^a-z0-9]+/g, " ").split(" ").filter((w) => w && !STOP.has(w));
}
const key = (name: string) => dishTokens(name).join(" ");
const nonGeneric = (toks: string[]) => toks.filter((t) => !GENERIC.has(t));
/** the word that says what kind of dish it is — the last one, past any "meals" / "combo" tail */
const kind = (toks: string[]) => { for (let i = toks.length - 1; i >= 0; i--) if (!SUFFIX.has(toks[i])) return toks[i]; return ""; };

/**
 * The library entry a menu dish most plausibly means, or null. Exact name first; then a library name
 * contained in the menu name (or the reverse — "Butter chicken" for "Butter chicken masala", "Plain dosa"
 * for "Dosa"); then the best word overlap, only when at least half the words agree, so "Chicken 65" is
 * never handed a biryani.
 *
 * Two guards, both learned from a wrong plate. A library key left with nothing but style words — "Veg
 * biryani" boils down to "biryani" — answers only a menu name as bare as itself, never "Hyderabadi
 * chicken dum biryani" (which the overlap then gives, rightly, to Chicken biryani). And a bare half
 * match must agree on what kind of dish it is: "Mango juice" shares a word with Mango lassi and is not one.
 */
export function findStandardRecipe(name: string): StandardRecipe | null {
  const k = key(name); if (!k) return null;
  const exact = RECIPE_LIBRARY.find((r) => key(r.dish) === k); if (exact) return exact;
  const mineToks = dishTokens(name); const mine = nonGeneric(mineToks);
  const extra = (r: StandardRecipe) => nonGeneric(dishTokens(r.dish)).filter((t) => !mine.includes(t)).length;
  const contained = RECIPE_LIBRARY.filter((r) => {
    const rk = key(r.dish); if (!(k.includes(rk) || rk.includes(k))) return false;
    const theirs = nonGeneric(dishTokens(r.dish));
    return theirs.length ? mine.length === 0 || theirs.some((t) => mine.includes(t)) : mine.length === 0;
  }).sort((a, b) => extra(a) - extra(b) || Math.abs(key(a.dish).length - k.length) - Math.abs(key(b.dish).length - k.length));
  if (contained.length) return contained[0];
  // a library dish's bracketed alias counts too: "Meen kuzhambu (fish curry)" answers to "Fish curry meals"
  let best: StandardRecipe | null = null; let score = 0; let agree = false;
  for (const r of RECIPE_LIBRARY) {
    for (const theirs of [dishTokens(r.dish), dishTokens(r.dish.replace(/[()]/g, " "))]) {
      const shared = theirs.filter((t) => mineToks.includes(t));
      if (!shared.some((t) => !GENERIC.has(t))) continue;
      const sc = shared.length / Math.max(mineToks.length, theirs.length);
      if (sc > score) { score = sc; best = r; agree = kind(theirs) === kind(mineToks); }
    }
  }
  return score > 0.5 || (score === 0.5 && agree) ? best : null;
}

/** A pantry quantity as a person reads it: 0.18 kg → "180 g", 0.015 l → "15 ml", 1.5 kg → "1.5 kg", 2 pcs → "2 pcs". */
export function fmtQty(qty: number, unit: string): string {
  const n = Number(qty) || 0;
  const trim = (x: number, d = 2) => String(Number(x.toFixed(d)));
  if (unit === "kg" && n < 1) return `${trim(n * 1000, 0)} g`;
  if (unit === "l" && n < 1) return `${trim(n * 1000, 0)} ml`;
  if (unit === "g" || unit === "ml") return `${trim(n, 1)} ${unit}`;
  if (unit === "pcs") return `${trim(n, 1)} pcs`;
  return `${trim(n, 2)} ${unit}`;
}
