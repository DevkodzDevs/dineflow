/* ── The standard recipe library ──────────────────────────────────────────────────────────────
   One plate, as an Indian restaurant sells it, in raw weights before cooking. When a dish on the menu
   is given a standard recipe, the pantry gains any ingredient it lacked and the kitchen starts drawing
   these amounts down the moment a ticket is started. Quantities are what a kitchen actually puts on the
   scale for one portion — the bulk lines that move stock, not every pinch.
   The figures follow the costing convention the trade uses — raw weight at yield: 200 g of chicken raw cooks to
   ~150 g on the plate, curry cut yields ~90%, boneless ~60% (chefdesk.in's plate-cost method) — and the portion
   catering guides give for a main, 170–225 g of cooked protein with its sauce. Where a menu's plate is bigger or
   smaller, the owner edits the lines: the library is a start, not a law.
   The vocabulary is fixed so that "Onion" in a biryani and "Onion" in a manchurian are the same pantry
   row, and so that every ingredient has one unit the pantry keeps it in. ─────────────────────── */

